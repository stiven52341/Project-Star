//! Writes generated Rust code as a Cargo package, ready to build.

use std::fs;
use std::io;
use std::path::{Path, PathBuf};

/// A Cargo package with programs compiled from StarScript.
///
/// Each program is a binary of the package; all of them share one build of
/// `star_script_runtime`. The package is its own workspace, so it can be
/// written anywhere, even inside another workspace's `target` folder.
#[derive(Debug, Clone)]
pub struct Package {
    name: String,
    runtime: PathBuf,
    programs: Vec<(String, String)>,
}

impl Package {
    /// A package called `name` that uses the runtime crate at `runtime`.
    ///
    /// # Errors
    ///
    /// Returns [`io::ErrorKind::InvalidInput`] if `name` is not a valid
    /// package name (letters, digits and `_`, not starting with a digit).
    pub fn new(name: &str, runtime: &Path) -> io::Result<Self> {
        check_name(name)?;
        Ok(Self {
            name: name.to_owned(),
            runtime: runtime.to_path_buf(),
            programs: Vec::new(),
        })
    }

    /// Adds a program: a binary called `name` with the generated `code`.
    ///
    /// # Errors
    ///
    /// Returns [`io::ErrorKind::InvalidInput`] if `name` is not valid, as
    /// for [`Package::new`].
    pub fn add_program(&mut self, name: &str, code: String) -> io::Result<()> {
        check_name(name)?;
        self.programs.push((name.to_owned(), code));
        Ok(())
    }

    /// Writes the package in `directory`, creating it if needed.
    ///
    /// # Errors
    ///
    /// Returns any error writing the files.
    pub fn write(&self, directory: &Path) -> io::Result<()> {
        let binaries = directory.join("src").join("bin");
        fs::create_dir_all(&binaries)?;
        fs::write(directory.join("Cargo.toml"), self.manifest())?;
        for (name, code) in &self.programs {
            fs::write(binaries.join(format!("{name}.rs")), code)?;
        }
        Ok(())
    }

    /// The `Cargo.toml` of the package.
    #[must_use]
    pub fn manifest(&self) -> String {
        let runtime = toml_string(&self.runtime.to_string_lossy());
        format!(
            "# Generated by the StarScript compiler.\n\
             [package]\n\
             name = \"{}\"\n\
             version = \"0.1.0\"\n\
             edition = \"2024\"\n\
             publish = false\n\
             \n\
             [dependencies]\n\
             star_script_runtime = {{ path = {runtime} }}\n\
             \n\
             # Its own workspace, wherever it is written.\n\
             [workspace]\n",
            self.name
        )
    }
}

/// Package and binary names: what Cargo and every platform accept.
fn check_name(name: &str) -> io::Result<()> {
    let valid = name
        .chars()
        .next()
        .is_some_and(|first| first.is_ascii_alphabetic() || first == '_')
        && name
            .chars()
            .all(|character| character.is_ascii_alphanumeric() || character == '_');
    if valid {
        Ok(())
    } else {
        Err(io::Error::new(
            io::ErrorKind::InvalidInput,
            format!("`{name}` is not a valid package or program name"),
        ))
    }
}

/// `text` as a TOML string, with `\` (Windows paths) and `"` escaped.
fn toml_string(text: &str) -> String {
    let escaped = text.replace('\\', "\\\\").replace('"', "\\\"");
    format!("\"{escaped}\"")
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn manifest_depends_on_the_runtime() {
        let package = Package::new("demo", Path::new("/engine/runtime")).expect("valid name");

        let manifest = package.manifest();

        assert!(manifest.contains("name = \"demo\""));
        assert!(manifest.contains("star_script_runtime = { path = \"/engine/runtime\" }"));
        assert!(manifest.contains("[workspace]"));
    }

    #[test]
    fn windows_paths_are_escaped() {
        assert_eq!(toml_string(r"C:\engine"), r#""C:\\engine""#);
    }

    #[test]
    fn names_must_be_valid_identifiers() {
        assert!(Package::new("my_game2", Path::new(".")).is_ok());
        for name in ["", "2game", "my-game", "a b", "../x"] {
            assert!(Package::new(name, Path::new(".")).is_err(), "{name:?}");
        }
    }
}
