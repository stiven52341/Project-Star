//! Writes generated Rust code as a Cargo package, ready to build.

use std::fs;
use std::io;
use std::path::{Path, PathBuf};

use crate::codegen::GeneratedProgram;

/// A Cargo package with programs compiled from StarScript.
///
/// Each program is a binary of the package; all of them share one build of
/// `star_script_runtime` (and of `star_engine`, if a program is a game). The
/// package is its own workspace, so it can be written anywhere, even inside
/// another workspace's `target` folder.
#[derive(Debug, Clone)]
pub struct Package {
    name: String,
    engine_crates: PathBuf,
    programs: Vec<(String, GeneratedProgram)>,
    lockfile: Option<String>,
}

impl Package {
    /// A package called `name` that uses the engine crates in the folder
    /// `engine_crates` (the `crates` folder of ProjectStar).
    ///
    /// # Errors
    ///
    /// Returns [`io::ErrorKind::InvalidInput`] if `name` is not a valid
    /// package name (letters, digits and `_`, not starting with a digit).
    pub fn new(name: &str, engine_crates: &Path) -> io::Result<Self> {
        check_name(name)?;
        Ok(Self {
            name: name.to_owned(),
            engine_crates: engine_crates.to_path_buf(),
            programs: Vec::new(),
            lockfile: None,
        })
    }

    /// The package with `lockfile` as its `Cargo.lock`: the versions of the
    /// dependencies it builds with.
    ///
    /// Given ProjectStar's own `Cargo.lock`, every package builds the same
    /// versions as the engine, so they can share one build of them; Cargo
    /// only adds the package itself and drops what it does not use.
    #[must_use]
    pub fn with_lockfile(mut self, lockfile: String) -> Self {
        self.lockfile = Some(lockfile);
        self
    }

    /// Adds a program: a binary called `name` with the generated code.
    ///
    /// # Errors
    ///
    /// Returns [`io::ErrorKind::InvalidInput`] if `name` is not valid, as
    /// for [`Package::new`].
    pub fn add_program(&mut self, name: &str, program: GeneratedProgram) -> io::Result<()> {
        check_name(name)?;
        self.programs.push((name.to_owned(), program));
        Ok(())
    }

    /// Writes the package in `directory`, creating it if needed.
    ///
    /// Files that already hold the same text are left alone: Cargo rebuilds
    /// a package whose files were written again, even if nothing changed.
    ///
    /// # Errors
    ///
    /// Returns any error reading or writing the files.
    pub fn write(&self, directory: &Path) -> io::Result<()> {
        let binaries = directory.join("src").join("bin");
        fs::create_dir_all(&binaries)?;
        write_if_changed(&directory.join("Cargo.toml"), &self.manifest())?;
        if let Some(lockfile) = &self.lockfile {
            write_if_changed(&directory.join(LOCKFILE), lockfile)?;
        }
        for (name, program) in &self.programs {
            write_if_changed(&binaries.join(format!("{name}.rs")), &program.code)?;
        }
        Ok(())
    }

    /// The `Cargo.toml` of the package.
    #[must_use]
    pub fn manifest(&self) -> String {
        let mut dependencies = vec![self.dependency(RUNTIME_CRATE)];
        if self
            .programs
            .iter()
            .any(|(_, program)| program.uses_engine())
        {
            dependencies.push(self.dependency(ENGINE_CRATE));
        }
        format!(
            "# Generated by the StarScript compiler.\n\
             [package]\n\
             name = \"{}\"\n\
             version = \"0.1.0\"\n\
             edition = \"2024\"\n\
             publish = false\n\
             \n\
             [dependencies]\n\
             {}\n\
             \n\
             # Its own workspace, wherever it is written.\n\
             [workspace]\n\
             \n\
             # The engine stays fast even in debug builds, as in ProjectStar,\n\
             # with the same profile so they can share builds.\n\
             [profile.dev]\n\
             opt-level = 1\n\
             \n\
             [profile.dev.package.\"*\"]\n\
             opt-level = 3\n\
             debug = \"line-tables-only\"\n",
            self.name,
            dependencies.join("\n")
        )
    }

    /// `crate = { path = "…" }` for an engine crate.
    fn dependency(&self, name: &str) -> String {
        let path = toml_string(&self.engine_crates.join(name).to_string_lossy());
        format!("{name} = {{ path = {path} }}")
    }
}

/// Crate that every generated program depends on.
const RUNTIME_CRATE: &str = "star_script_runtime";
/// Crate that games depend on.
const ENGINE_CRATE: &str = "star_engine";
/// The file with the versions of the package's dependencies.
const LOCKFILE: &str = "Cargo.lock";

/// Writes `text` to `path` unless it already holds exactly that.
fn write_if_changed(path: &Path, text: &str) -> io::Result<()> {
    match fs::read_to_string(path) {
        Ok(current) if current == text => Ok(()),
        Ok(_) => fs::write(path, text),
        Err(error) if error.kind() == io::ErrorKind::NotFound => fs::write(path, text),
        Err(error) => Err(error),
    }
}

/// Package and binary names: what Cargo and every platform accept.
fn check_name(name: &str) -> io::Result<()> {
    let valid = name
        .chars()
        .next()
        .is_some_and(|first| first.is_ascii_alphabetic() || first == '_')
        && name
            .chars()
            .all(|character| character.is_ascii_alphanumeric() || character == '_');
    if valid {
        Ok(())
    } else {
        Err(io::Error::new(
            io::ErrorKind::InvalidInput,
            format!("`{name}` is not a valid package or program name"),
        ))
    }
}

/// `text` as a TOML string, with `\` (Windows paths) and `"` escaped.
fn toml_string(text: &str) -> String {
    let escaped = text.replace('\\', "\\\\").replace('"', "\\\"");
    format!("\"{escaped}\"")
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::codegen::EntryPoint;

    fn program(entry_point: EntryPoint) -> GeneratedProgram {
        GeneratedProgram {
            code: String::new(),
            entry_point,
        }
    }

    #[test]
    fn programs_depend_on_the_runtime() {
        let mut package = Package::new("demo", Path::new("/engine")).expect("valid name");
        package
            .add_program("tool", program(EntryPoint::Main))
            .expect("valid name");

        let manifest = package.manifest();

        assert!(manifest.contains("name = \"demo\""));
        let runtime = Path::new("/engine").join("star_script_runtime");
        assert!(manifest.contains(&format!(
            "star_script_runtime = {{ path = {} }}",
            toml_string(&runtime.to_string_lossy())
        )));
        assert!(!manifest.contains("star_engine"));
        assert!(manifest.contains("[workspace]"));
    }

    #[test]
    fn dependencies_keep_only_their_line_tables() {
        let manifest = game_package().manifest();

        assert!(manifest.contains("opt-level = 3\ndebug = \"line-tables-only\"\n"));
    }

    #[test]
    fn games_also_depend_on_the_engine() {
        let mut package = Package::new("demo", Path::new("/engine")).expect("valid name");
        package
            .add_program("game", program(EntryPoint::Game))
            .expect("valid name");

        assert!(package.manifest().contains("star_engine = { path = "));
    }

    /// A folder of its own under the system's temporary folder, emptied first.
    fn test_directory(name: &str) -> PathBuf {
        let directory = std::env::temp_dir().join(format!("star_script_package_{name}"));
        let _ = fs::remove_dir_all(&directory);
        directory
    }

    fn game_package() -> Package {
        let mut package = Package::new("demo", Path::new("/engine")).expect("valid name");
        package
            .add_program(
                "game",
                GeneratedProgram {
                    code: "fn main() {}\n".to_owned(),
                    entry_point: EntryPoint::Main,
                },
            )
            .expect("valid name");
        package
    }

    #[test]
    fn the_lockfile_is_written_when_given() {
        let directory = test_directory("lockfile");

        game_package()
            .with_lockfile("version = 4\n".to_owned())
            .write(&directory)
            .expect("written");

        let lockfile = fs::read_to_string(directory.join(LOCKFILE)).expect("lockfile");
        assert_eq!(lockfile, "version = 4\n");
    }

    #[test]
    fn without_a_lockfile_cargo_chooses_the_versions() {
        let directory = test_directory("no_lockfile");

        game_package().write(&directory).expect("written");

        assert!(!directory.join(LOCKFILE).exists());
    }

    #[test]
    fn unchanged_files_are_not_written_again() {
        let directory = test_directory("unchanged");
        let package = game_package();
        package.write(&directory).expect("written");
        let code = directory.join("src").join("bin").join("game.rs");
        let old = std::time::SystemTime::UNIX_EPOCH;
        fs::File::options()
            .write(true)
            .open(&code)
            .and_then(|file| file.set_modified(old))
            .expect("modification time set");

        package.write(&directory).expect("written again");

        let modified = fs::metadata(&code)
            .and_then(|metadata| metadata.modified())
            .expect("modification time");
        assert_eq!(modified, old);
    }

    #[test]
    fn changed_files_are_written_again() {
        let directory = test_directory("changed");
        game_package().write(&directory).expect("written");
        let mut package = Package::new("demo", Path::new("/engine")).expect("valid name");
        package
            .add_program(
                "game",
                GeneratedProgram {
                    code: "fn main() { println!(); }\n".to_owned(),
                    entry_point: EntryPoint::Main,
                },
            )
            .expect("valid name");

        package.write(&directory).expect("written again");

        let code =
            fs::read_to_string(directory.join("src").join("bin").join("game.rs")).expect("code");
        assert_eq!(code, "fn main() { println!(); }\n");
    }

    #[test]
    fn windows_paths_are_escaped() {
        assert_eq!(toml_string(r"C:\engine"), r#""C:\\engine""#);
    }

    #[test]
    fn names_must_be_valid_identifiers() {
        assert!(Package::new("my_game2", Path::new(".")).is_ok());
        for name in ["", "2game", "my-game", "a b", "../x"] {
            assert!(Package::new(name, Path::new(".")).is_err(), "{name:?}");
        }
    }
}
