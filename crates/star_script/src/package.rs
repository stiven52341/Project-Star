//! Writes generated Rust code as a Cargo package, ready to build.

use std::fs;
use std::io;
use std::path::{Path, PathBuf};

use crate::codegen::GeneratedProgram;

/// A Cargo package with programs compiled from StarScript.
///
/// Each program is a binary of the package; all of them share one build of
/// `star_script_runtime` (and of `star_engine`, if a program is a game). The
/// package is its own workspace, so it can be written anywhere, even inside
/// another workspace's `target` folder.
#[derive(Debug, Clone)]
pub struct Package {
    name: String,
    engine_crates: PathBuf,
    programs: Vec<(String, GeneratedProgram)>,
}

impl Package {
    /// A package called `name` that uses the engine crates in the folder
    /// `engine_crates` (the `crates` folder of ProjectStar).
    ///
    /// # Errors
    ///
    /// Returns [`io::ErrorKind::InvalidInput`] if `name` is not a valid
    /// package name (letters, digits and `_`, not starting with a digit).
    pub fn new(name: &str, engine_crates: &Path) -> io::Result<Self> {
        check_name(name)?;
        Ok(Self {
            name: name.to_owned(),
            engine_crates: engine_crates.to_path_buf(),
            programs: Vec::new(),
        })
    }

    /// Adds a program: a binary called `name` with the generated code.
    ///
    /// # Errors
    ///
    /// Returns [`io::ErrorKind::InvalidInput`] if `name` is not valid, as
    /// for [`Package::new`].
    pub fn add_program(&mut self, name: &str, program: GeneratedProgram) -> io::Result<()> {
        check_name(name)?;
        self.programs.push((name.to_owned(), program));
        Ok(())
    }

    /// Writes the package in `directory`, creating it if needed.
    ///
    /// # Errors
    ///
    /// Returns any error writing the files.
    pub fn write(&self, directory: &Path) -> io::Result<()> {
        let binaries = directory.join("src").join("bin");
        fs::create_dir_all(&binaries)?;
        fs::write(directory.join("Cargo.toml"), self.manifest())?;
        for (name, program) in &self.programs {
            fs::write(binaries.join(format!("{name}.rs")), &program.code)?;
        }
        Ok(())
    }

    /// The `Cargo.toml` of the package.
    #[must_use]
    pub fn manifest(&self) -> String {
        let mut dependencies = vec![self.dependency(RUNTIME_CRATE)];
        if self
            .programs
            .iter()
            .any(|(_, program)| program.uses_engine())
        {
            dependencies.push(self.dependency(ENGINE_CRATE));
        }
        format!(
            "# Generated by the StarScript compiler.\n\
             [package]\n\
             name = \"{}\"\n\
             version = \"0.1.0\"\n\
             edition = \"2024\"\n\
             publish = false\n\
             \n\
             [dependencies]\n\
             {}\n\
             \n\
             # Its own workspace, wherever it is written.\n\
             [workspace]\n\
             \n\
             # The engine stays fast even in debug builds, as in ProjectStar.\n\
             [profile.dev]\n\
             opt-level = 1\n\
             \n\
             [profile.dev.package.\"*\"]\n\
             opt-level = 3\n",
            self.name,
            dependencies.join("\n")
        )
    }

    /// `crate = { path = "…" }` for an engine crate.
    fn dependency(&self, name: &str) -> String {
        let path = toml_string(&self.engine_crates.join(name).to_string_lossy());
        format!("{name} = {{ path = {path} }}")
    }
}

/// Crate that every generated program depends on.
const RUNTIME_CRATE: &str = "star_script_runtime";
/// Crate that games depend on.
const ENGINE_CRATE: &str = "star_engine";

/// Package and binary names: what Cargo and every platform accept.
fn check_name(name: &str) -> io::Result<()> {
    let valid = name
        .chars()
        .next()
        .is_some_and(|first| first.is_ascii_alphabetic() || first == '_')
        && name
            .chars()
            .all(|character| character.is_ascii_alphanumeric() || character == '_');
    if valid {
        Ok(())
    } else {
        Err(io::Error::new(
            io::ErrorKind::InvalidInput,
            format!("`{name}` is not a valid package or program name"),
        ))
    }
}

/// `text` as a TOML string, with `\` (Windows paths) and `"` escaped.
fn toml_string(text: &str) -> String {
    let escaped = text.replace('\\', "\\\\").replace('"', "\\\"");
    format!("\"{escaped}\"")
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::codegen::EntryPoint;

    fn program(entry_point: EntryPoint) -> GeneratedProgram {
        GeneratedProgram {
            code: String::new(),
            entry_point,
        }
    }

    #[test]
    fn programs_depend_on_the_runtime() {
        let mut package = Package::new("demo", Path::new("/engine")).expect("valid name");
        package
            .add_program("tool", program(EntryPoint::Main))
            .expect("valid name");

        let manifest = package.manifest();

        assert!(manifest.contains("name = \"demo\""));
        let runtime = Path::new("/engine").join("star_script_runtime");
        assert!(manifest.contains(&format!(
            "star_script_runtime = {{ path = {} }}",
            toml_string(&runtime.to_string_lossy())
        )));
        assert!(!manifest.contains("star_engine"));
        assert!(manifest.contains("[workspace]"));
    }

    #[test]
    fn games_also_depend_on_the_engine() {
        let mut package = Package::new("demo", Path::new("/engine")).expect("valid name");
        package
            .add_program("game", program(EntryPoint::Game))
            .expect("valid name");

        assert!(package.manifest().contains("star_engine = { path = "));
    }

    #[test]
    fn windows_paths_are_escaped() {
        assert_eq!(toml_string(r"C:\engine"), r#""C:\\engine""#);
    }

    #[test]
    fn names_must_be_valid_identifiers() {
        assert!(Package::new("my_game2", Path::new(".")).is_ok());
        for name in ["", "2game", "my-game", "a b", "../x"] {
            assert!(Package::new(name, Path::new(".")).is_err(), "{name:?}");
        }
    }
}
